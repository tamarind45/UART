module d_ff #(
  parameter WIDTH = 1
)(
  input  logic             i_clk,
  input  logic             i_rst,
  input  logic             i_clr,
  input  logic             i_en,
  input  logic [WIDTH-1:0] i_d,
  output logic [WIDTH-1:0] o_q
);

//====================================DECLARATION==============================================================//

  reg [WIDTH-1:0] q_reg;

  assign o_q = q_reg;

//============================================================================================================//

//====================================COMBINATIONAL LOGIC======================================================//

//============================================================================================================//

//====================================SEQUENTIAL LOGIC=========================================================//

  always_ff @(posedge i_clk or posedge i_rst) begin
    if (i_rst)      q_reg <= '0;
    else if (i_clr) q_reg <= '0;
    else if (i_en)  q_reg <= i_d;
  end

//============================================================================================================//

endmodule
